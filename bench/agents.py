"""Who opened a pull request: the agents the benchmark recognises, and by what.

Every signature below was checked against real pull requests through the API
before it was written down; bench/README.md has what was checked and what each
one is known to miss. The evidence comes in two strengths, kept apart:

* **Opened by.** The pull request itself says an agent made it: its author is
  the agent's GitHub App, its body carries the footer or session link the agent
  writes, or its branch has the prefix the agent names its branches with.
* **Assisted by.** Only something weaker says so: a commit trailer or a bot as
  commit author, a session link without the agent's own footer, a branch prefix
  people also type by hand. Such a pull request is neither the agent's nor
  cleanly a person's, so it is in neither group -- the agent groups must not
  claim work a person opened, and the human group must not quietly contain
  agent work.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

HUMAN = "human"
#: Groups a pull request can land in besides an agent's name and ``HUMAN``.
ASSISTED = "assisted"
AMBIGUOUS = "ambiguous"
BOT = "bot"

#: Accounts that are bots without being GitHub Apps: ``k8s-ci-robot``,
#: ``renovate-bot``. A person whose login merely ends in "bot" is lost from the
#: human group, which costs less than a bot counted as a person.
_BOT_LOGIN = re.compile(r"(?i)(?:^|[-_])(?:ro)?bot$|\[bot\]$")


@dataclass(frozen=True)
class Agent:
    name: str
    title: str
    #: GitHub search terms that find candidates. Search is a net, not a
    #: verdict: its text matching is loose (a phrase also matches in comments,
    #: and in any order), so every candidate is confirmed by ``identify``.
    search: str
    #: GitHub App logins that open pull requests as this agent.
    apps: frozenset[str] = frozenset()
    body: tuple[re.Pattern[str], ...] = ()
    #: Branch prefixes the agent uses when it opens a pull request under a
    #: person's account.
    branches: tuple[str, ...] = ()
    assisted_body: tuple[re.Pattern[str], ...] = ()
    assisted_branches: tuple[re.Pattern[str], ...] = ()
    #: Matched against each commit's message, author name and author email.
    commits: tuple[re.Pattern[str], ...] = ()


def _patterns(*sources: str) -> tuple[re.Pattern[str], ...]:
    return tuple(re.compile(source) for source in sources)


AGENTS: dict[str, Agent] = {
    agent.name: agent
    for agent in (
        Agent(
            name="copilot",
            title="GitHub Copilot coding agent",
            search="author:app/copilot-swe-agent",
            apps=frozenset({"copilot-swe-agent"}),
            # The agent always works on a copilot/ branch, but so does a person
            # who took over its branch, and Copilot in an editor; only the App
            # as author says the agent opened it. Both commit as a
            # ``…+Copilot@users.noreply.github.com`` address.
            assisted_branches=_patterns(r"^copilot/"),
            commits=_patterns(
                r"copilot-swe-agent\[bot\]", r"\+Copilot@users\.noreply\.github\.com"
            ),
        ),
        Agent(
            name="codex",
            title="OpenAI Codex",
            search='(author:app/chatgpt-codex-connector OR head:codex/ OR "Codex Task")',
            apps=frozenset({"chatgpt-codex-connector"}),
            body=_patterns(r"chatgpt\.com/codex/(?:cloud/)?tasks/"),
            # Codex opens its pull requests under the person's account, and most
            # carry no task link: the branch Codex names is often all there is.
            branches=("codex/",),
        ),
        Agent(
            name="claude",
            title="Claude Code",
            search=(
                "(author:app/claude OR head:claude/"
                ' OR "Generated with Claude Code" OR "Generated by Claude Code")'
            ),
            apps=frozenset({"claude"}),
            body=_patterns(r"Generated (?:with|by) \[?Claude Code\]?", r"claude\.ai/code/session_"),
            branches=("claude/",),
            commits=_patterns(
                r"noreply@anthropic\.com", r"Generated with \[?Claude Code", r"\bclaude\[bot\]"
            ),
        ),
        Agent(
            name="cursor",
            title="Cursor",
            search=(
                '(author:app/cursor OR head:cursor/ OR "cursor.com/agents" OR "Made with Cursor")'
            ),
            apps=frozenset({"cursor"}),
            body=_patterns(
                r"<!-- CURSOR_AGENT_PR_BODY_END -->",
                r"cursor\.com/agents/bc-",
                r"cursor\.com/background-agent\?bcId=",
                r"Made with \[Cursor\]\(https://cursor\.com\)",
            ),
            branches=("cursor/",),
            commits=_patterns(r"cursoragent@cursor\.com"),
        ),
        Agent(
            name="devin",
            title="Devin",
            search="author:app/devin-ai-integration",
            apps=frozenset({"devin-ai-integration"}),
            # Devin's own pull requests link their session too; the link in a
            # person's pull request says only that Devin was involved.
            assisted_body=_patterns(r"app\.devin\.ai/sessions/"),
            assisted_branches=_patterns(r"^devin/"),
            commits=_patterns(r"devin-ai-integration\[bot\]"),
        ),
        Agent(
            name="jules",
            title="Google Jules",
            search="author:app/google-labs-jules",
            apps=frozenset({"google-labs-jules"}),
            assisted_body=_patterns(r"jules\.google\.com/task/"),
            assisted_branches=_patterns(r"^jules-\d{10,}-"),
            commits=_patterns(r"google-labs-jules\[bot\]"),
        ),
    )
}


@dataclass(frozen=True)
class Identity:
    #: An agent's name, ``HUMAN``, ``ASSISTED``, ``AMBIGUOUS`` or ``BOT``.
    group: str
    #: What decided it, for an agent: ``app``, ``body``, ``branch``.
    via: tuple[str, ...] = ()


def identify(pr: Mapping[str, Any]) -> Identity:
    """Which group a pull request belongs to, from its author, body, branch and commits.

    ``pr`` is a pull request as the benchmark's GraphQL query returns it.
    """

    author = pr.get("author") or {}
    login = str(author.get("login") or "")
    branch = str(pr.get("headRefName") or "")
    body = str(pr.get("body") or "")

    if author.get("__typename") == "Bot":
        for agent in AGENTS.values():
            if login in agent.apps:
                # The App as author is the one signature nobody else can put on
                # a pull request; a body quoting another tool does not undo it.
                return Identity(agent.name, ("app",))
        return Identity(BOT)

    opened: dict[str, tuple[str, ...]] = {}
    for agent in AGENTS.values():
        via = tuple(
            kind
            for kind, found in (
                ("body", any(pattern.search(body) for pattern in agent.body)),
                ("branch", branch.startswith(agent.branches) if agent.branches else False),
            )
            if found
        )
        if via:
            opened[agent.name] = via
    if len(opened) > 1:
        return Identity(AMBIGUOUS, tuple(sorted(opened)))
    if opened:
        ((name, via),) = opened.items()
        return Identity(name, via)
    if _BOT_LOGIN.search(login):
        return Identity(BOT)
    if assisted_by(pr):
        return Identity(ASSISTED, tuple(sorted(assisted_by(pr))))
    return Identity(HUMAN)


def assisted_by(pr: Mapping[str, Any]) -> set[str]:
    """Agents that left a weaker trace: a commit, a session link, a branch prefix."""

    branch = str(pr.get("headRefName") or "")
    body = str(pr.get("body") or "")
    commits = []
    for node in (pr.get("commits") or {}).get("nodes") or []:
        commit = (node.get("commit") if isinstance(node, dict) else None) or {}
        author = commit.get("author") or {}
        commits.append(
            f"{commit.get('message') or ''}\n{author.get('name') or ''}\n{author.get('email') or ''}"
        )
    found: set[str] = set()
    for agent in AGENTS.values():
        if (
            any(pattern.search(body) for pattern in agent.assisted_body)
            or any(pattern.search(branch) for pattern in agent.assisted_branches)
            or any(pattern.search(text) for pattern in agent.commits for text in commits)
        ):
            found.add(agent.name)
    return found


def plainly_not_human(pr: Mapping[str, Any]) -> bool:
    """What the search results alone rule out, before fetching a pull request's body.

    Only the author and the branch are there, so this errs toward keeping a
    candidate: ``identify`` on the full pull request has the last word.
    """

    author = pr.get("author") or {}
    if author.get("__typename") == "Bot" or _BOT_LOGIN.search(str(author.get("login") or "")):
        return True
    branch = str(pr.get("headRefName") or "")
    return any(
        (agent.branches and branch.startswith(agent.branches))
        or any(pattern.search(branch) for pattern in agent.assisted_branches)
        for agent in AGENTS.values()
    )
